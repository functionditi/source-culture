"""Generate an idempotent production import of curated editorial listings only.

This never reads the local database, outbox, demo fixtures, or private uploads.
Existing records (including withdrawals and editorial changes) are untouched.
"""
import json
from pathlib import Path
from urllib.parse import parse_qsl, urlencode, urlparse, urlunparse

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'supabase/migrations/202610260002_editorial.sql'


def generate():
    curated = json.loads((ROOT / 'data/editorial.json').read_text())
    records = curated['sources'] + curated['entries']
    for entry in records:
        source = entry['content'].get('source')
        if source:
            url = urlparse(source.get('url', ''))
            query = [(k, v) for k, v in parse_qsl(url.query) if not k.startswith('utm_')]
            source['canonical_url'] = urlunparse((url.scheme.lower(), url.netloc.lower(), url.path.rstrip('/'), '', urlencode(query), ''))
            source['canonical_doi'] = source.get('doi', '').lower().removeprefix('https://doi.org/')
    payload = json.dumps(records, ensure_ascii=False, indent=2)
    if '$editorial$' in payload:
        raise ValueError('Editorial text contains the SQL delimiter.')
    return """-- Generated by python3 -m server.build_supabase_seed.
-- Editorial descriptions of existing work, not contributor permission records.
-- No owner email, fabricated consent, local submissions, or demo data is imported.
do $migration$
declare item jsonb; citation jsonb; inserted text; revision text;
begin
  for item in select value from jsonb_array_elements($editorial$
""" + payload + """
$editorial$::jsonb) loop
    inserted := null;
    insert into source_culture.entities(id,kind,slug,status)
      values(item->>'id',item->>'kind',item->>'slug','published')
      on conflict(id) do nothing returning id into inserted;
    if inserted is not null then
      revision := 'revision-'||inserted;
      insert into source_culture.revisions(id,entity_id,number,content,state)
        values(revision,inserted,1,item->'content','published');
      update source_culture.entities set published_revision_id=revision where id=inserted;
      for citation in select value from jsonb_array_elements(coalesce(item->'citations','[]')) loop
        insert into source_culture.citations(revision_id,source_id,block_id,relationship,locator,annotation)
          values(revision,citation->>'source_id',nullif(citation->>'block_id',''),citation->>'relationship',
            coalesce(citation->>'locator',''),coalesce(citation->>'annotation',''));
      end loop;
    end if;
  end loop;
end $migration$;
"""


if __name__ == '__main__':
    OUTPUT.write_text(generate())
    print('Generated', OUTPUT.relative_to(ROOT))
